"""RESULTS_SEMSEG_NATIVE.{md,csv} from bench_semseg_native.py output (plot: plot_semseg_native.py).

No hand-typed numbers: everything comes from output/compare_native/semseg_native_<backend>.csv.
Refuses partial (--limit) runs: every row must be scored on all 500 val images.

  uv run --project ../../D-FINE-seg python make_results_native.py
  uv run --project ../../D-FINE-seg python plot_semseg_native.py --latency e2e --xmax 25 \
      --pin Mask2Former-Swin-L --out semseg_native.png   # + --latency engine -> semseg_native_engine.png
"""

import os

import pandas as pd

from paths import OUTPUT, RIV

IN = OUTPUT / "compare_native"
N_VAL = 500
FAMILY = {
    "dfine": "D-FINE-seg",
    "yolo": "YOLO26-sem",
    "segformer": "SegFormer",
    "effvit": "EfficientViT-Seg",
    "mask2former": "Mask2Former",
}


def load(backend: str) -> pd.DataFrame | None:
    p = IN / f"semseg_native_{backend}.csv"
    if not p.exists():
        return None
    df = pd.read_csv(p, index_col=0)
    short = df.index[df["n_images"] != N_VAL].tolist()
    if short:
        raise SystemExit(f"{p.name}: {short} not scored on all {N_VAL} images (a --limit run?)")
    return df


def pct(x):
    return "" if pd.isna(x) else f"{100 * x:.1f}"


def md_table(rows: list[list], head: list[str]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main_table(df: pd.DataFrame) -> str:
    best = {"mIoU": df["mIoU"].max(), "pixel_acc": df["pixel_acc"].max()}
    rows = []
    for fam in FAMILY:
        for name, r in df[df["family"] == fam].sort_values("engine_ms").iterrows():
            b = lambda k, v: f"**{v}**" if r[k] == best[k] else v  # noqa: E731
            rows.append(
                [
                    name,
                    r["params_m"],
                    r["gmacs"],
                    b("mIoU", pct(r["mIoU"])),
                    b("pixel_acc", pct(r["pixel_acc"])),
                    f"{r['e2e_ms']:.2f}",
                    f"{r['engine_ms']:.2f}",
                    ""
                    if pd.isna(r["published_mIoU"])
                    else f"{r['published_mIoU']:.1f} ({r['published_protocol']})",
                ]
            )
    return md_table(
        rows,
        [
            "model",
            "params (M)",
            "GMACs",
            "**mIoU**",
            "pixel acc",
            "e2e ms",
            "engine ms",
            "published mIoU (protocol)",
        ],
    )


if __name__ == "__main__":
    trt = load("trt")
    if trt is None:
        raise SystemExit(f"no {IN}/semseg_native_trt.csv - run bench_semseg_native.py first")
    torch_df, slide = load("torch"), load("slide")

    if "engine" in trt:  # repo-relative, so the published CSV carries no local absolute paths
        trt["engine"] = [
            os.path.relpath(p if os.path.isabs(p) else RIV / p, RIV) for p in trt["engine"]
        ]
    trt.to_csv(RIV / "RESULTS_SEMSEG_NATIVE.csv")

    parts = [
        "# Cityscapes semantic segmentation at native 1024x2048: results\n",
        "Generated by `make_results_native.py` from `bench_semseg_native.py` output; no hand-typed "
        "numbers. Protocol: [`PROTOCOL.md` §11]"
        "(PROTOCOL.md#11-native-resolution-semantic-segmentation). 500 val images, whole "
        "1024x2048 frame, one forward pass, scored at 1024x2048 by one scorer. TensorRT "
        "10.13.3.9 fp16, batch 1, idle GPU. Each framework runs its own pre/postprocess.\n",
        "![mIoU vs latency](semseg_native.png)\n",
        main_table(trt),
        "\n`e2e ms` = the framework's own call (decode and D2H off the clock). `engine ms` = TRT "
        "execute only, same loop for every engine. GMACs are recounted with one counter "
        "(`model_stats.py`) at 1024x2048.\n",
    ]
    if torch_df is not None:
        g = trt[["mIoU"]].join(torch_df[["mIoU"]], rsuffix="_torch", how="inner")
        rows = [
            [n, pct(r["mIoU"]), pct(r["mIoU_torch"]), f"{100 * (r['mIoU'] - r['mIoU_torch']):+.2f}"]
            for n, r in g.iterrows()
        ]
        parts += [
            "## TRT fp16 correctness gate (same pre/post, PyTorch fp32 model)\n",
            md_table(rows, ["model", "TRT fp16", "torch", "delta"]),
            "",
        ]
    if slide is not None:
        rows = [
            [
                n,
                pct(r["mIoU"]),
                f"{r['published_mIoU']:.1f}",
                f"{100 * r['mIoU'] - r['published_mIoU']:+.2f}",
            ]
            for n, r in slide.iterrows()
        ]
        parts += [
            "## SegFormer reproduction (their sliding-window protocol, torch)\n",
            md_table(rows, ["model", "ours (slide)", "paper", "delta"]),
            "",
        ]
    iou = [c for c in trt.columns if c.startswith("iou_")]
    rows = [[n] + [pct(r[c]) for c in iou] for n, r in trt.iterrows()]
    parts += ["## Per-class IoU (TRT)\n", md_table(rows, ["model"] + [c[4:] for c in iou])]
    (RIV / "RESULTS_SEMSEG_NATIVE.md").write_text("\n".join(parts) + "\n")
    print(f"wrote RESULTS_SEMSEG_NATIVE.md / .csv in {RIV}; plot: plot_semseg_native.py")
